// newSignedUpdateMessage has the member of g create an Update with SelfUpdate and sign it as a
// PublicMessage. It returns the proposal and the parsed message.
func newSignedUpdateMessage(t *testing.T, g *Group, sig *ciphersuite.SignaturePrivateKey) (*Proposal, *framing.PublicMessage) {
	t.Helper()
	update, err := g.SelfUpdate(sig)
	if err != nil {
		t.Fatalf("SelfUpdate: %v", err)
	}
	raw, err := g.SignProposalAsPublicMessage(update, sig)
	if err != nil {
		t.Fatalf("SignProposalAsPublicMessage: %v", err)
	}
	msg, err := framing.UnmarshalMLSMessage(raw)
	if err != nil {
		t.Fatalf("UnmarshalMLSMessage: %v", err)
	}
	pm, ok := msg.AsPublic()
	if !ok {
		t.Fatal("update is not a PublicMessage")
	}
	return update, pm
}

// publicMessageProposalRef returns the ProposalRef of a proposal received as pm, computed as the receivers do.
func publicMessageProposalRef(pm *framing.PublicMessage, cs ciphersuite.CipherSuite) []byte {
	ac := &framing.AuthenticatedContent{WireFormat: framing.WireFormatPublicMessage, Content: pm.Content, Auth: pm.Auth}
	return ComputeProposalRef(ac.Marshal(), cs)
}

// TestCommitRejectsCommitterUpdateByReference checks that a commit cannot
// include an Update generated by its own committer, even by reference.
// An Update from another member remains valid when included by reference.
func TestCommitRejectsCommitterUpdateByReference(t *testing.T) {
	t.Run("reject/committer_refuses_own_update_by_reference", func(t *testing.T) {
		m := newUpdateProposalTestMembers(t)
		update, pm := newSignedUpdateMessage(t, m.bobGroup, m.bob.sigPriv)
		for _, g := range []*Group{m.aliceGroup, m.charlieGroup} {
			if err := g.ProcessPublicMessage(pm); err != nil {
				t.Fatalf("ProcessPublicMessage(bob update): %v", err)
			}
		}
		m.bobGroup.RegisterProposalRef(update, publicMessageProposalRef(pm, m.bobGroup.cipherSuite))

		_, err := m.bobGroup.Commit(m.bob.sigPriv, m.bob.sigPub, nil)
		if !errors.Is(err, ErrInvalidProposal) || !strings.Contains(err.Error(), "generated by the committer") {
			t.Fatalf("Commit(bob) with his own Update by reference: err = %v, want ErrInvalidProposal", err)
		}
	})

	// The honest API refuses to build this commit, so the test builds it by hand: bob's empty commit
	// with the reference appended and re-signed. alice's proposal filter runs before the UpdatePath is
	// processed, so the path does not have to match the tree.
	t.Run("reject/receiver_refuses_commit_with_own_update_by_reference", func(t *testing.T) {
		m := newUpdateProposalTestMembers(t)
		update, pm := newSignedUpdateMessage(t, m.bobGroup, m.bob.sigPriv)
		for _, g := range []*Group{m.aliceGroup, m.charlieGroup} {
			if err := g.ProcessPublicMessage(pm); err != nil {
				t.Fatalf("ProcessPublicMessage(bob update): %v", err)
			}
		}
		ref := publicMessageProposalRef(pm, m.bobGroup.cipherSuite)
		m.bobGroup.RegisterProposalRef(update, ref)
		m.bobGroup.ClearProposals()
		base, err := m.bobGroup.Commit(m.bob.sigPriv, m.bob.sigPub, nil)
		if err != nil {
			t.Fatalf("Commit(bob, empty base): %v", err)
		}
		body, ok := base.authenticatedContent.Content.Body.(framing.CommitBody)
		if !ok {
			t.Fatal("base commit has no commit body")
		}
		commit, err := UnmarshalCommit(body.Data)
		if err != nil {
			t.Fatalf("UnmarshalCommit(base): %v", err)
		}
		commit.Proposals = append(commit.Proposals, ProposalOrRef{ProposalRef: ref})
		forged := *base.authenticatedContent
		forged.Content.Body = framing.CommitBody{Data: commit.Marshal()}
		sig, err := ciphersuite.SignWithLabel(m.bob.sigPriv, "FramedContentTBS", forged.MarshalTBS())
		if err != nil {
			t.Fatalf("re-signing the forged commit: %v", err)
		}
		forged.Auth.Signature = sig

		err = m.aliceGroup.ProcessReceivedCommit(&forged, treesync.LeafIndex(m.bobGroup.ownLeafIndex), m.aliceGroup.myLeafEncryptionKey)
		if !errors.Is(err, ErrInvalidProposal) || !strings.Contains(err.Error(), "generated by the committer") {
			t.Fatalf("alice.ProcessReceivedCommit(bob's commit with his own Update by reference): err = %v, want ErrInvalidProposal", err)
		}
		if got := m.aliceGroup.epoch.AsUint64(); got != 1 {
			t.Fatalf("refused commit advanced alice to epoch %d, want 1", got)
		}
	})

	t.Run("control/member_update_by_reference_accepted", func(t *testing.T) {
		m := newUpdateProposalTestMembers(t)
		_, pm := newSignedUpdateMessage(t, m.aliceGroup, m.alice.sigPriv)
		for _, g := range []*Group{m.bobGroup, m.charlieGroup} {
			if err := g.ProcessPublicMessage(pm); err != nil {
				t.Fatalf("ProcessPublicMessage(alice update): %v", err)
			}
		}

		sc, err := m.bobGroup.Commit(m.bob.sigPriv, m.bob.sigPub, nil)
		if err != nil {
			t.Fatalf("Commit(bob) with alice's Update by reference: %v", err)
		}
		if err := m.charlieGroup.ProcessReceivedCommit(sc.authenticatedContent, treesync.LeafIndex(m.bobGroup.ownLeafIndex), m.charlieGroup.myLeafEncryptionKey); err != nil {
			t.Fatalf("charlie.ProcessReceivedCommit(bob's commit with alice's Update by reference): %v", err)
		}
	})
}
