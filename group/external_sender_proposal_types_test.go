package group

// An external sender may only send proposals of type add, remove, psk, reinit and
// group_context_extensions (RFC 9420 §12.1.8). ExternalInit can only be used in an external commit
// (RFC 9420 §12.1.6).
//
// processProposalContent used to store an ExternalInit sent by an external sender as an ordinary
// proposal, and IsExternal was never set on the FilteredProposal values built by the commit path, so the
// external sender rule never ran. The stored ExternalInit then made every regular Commit fail with
// "external init from internal sender" until it was revoked or cleared.

import (
	"bytes"
	"errors"
	"strings"
	"testing"

	"github.com/thomas-vilte/mls-go/ciphersuite"
	"github.com/thomas-vilte/mls-go/credentials"
	"github.com/thomas-vilte/mls-go/framing"
	"github.com/thomas-vilte/mls-go/keypackages"
)

// newGroupWithExternalSender creates a one-member group whose GroupContext carries the external_senders
// extension (0x0005) with a signature key generated by the test. It returns the group, the member's
// signature key and the external sender's signature key.
func newGroupWithExternalSender(t *testing.T) (grp *Group, member, ext *ciphersuite.SignaturePrivateKey) {
	t.Helper()

	cred, _, err := credentials.GenerateCredentialWithKey([]byte("alice"))
	if err != nil {
		t.Fatalf("GenerateCredentialWithKey: %v", err)
	}
	kp, kpPriv, err := keypackages.Generate(cred, keypackages.MLS128DHKEMP256)
	if err != nil {
		t.Fatalf("keypackages.Generate: %v", err)
	}
	memberSig := ciphersuite.NewSignaturePrivateKey(kpPriv.SignatureKey)

	extSig, err := ciphersuite.GenerateSignaturePrivateKeyForCS(ciphersuite.MLS128DHKEMP256)
	if err != nil {
		t.Fatalf("GenerateSignaturePrivateKeyForCS: %v", err)
	}
	extData := buildExternalSendersExtData(t, extSig.PublicKey().AsSlice(),
		credentials.NewBasicCredentialFromString("external-sender").Marshal())

	gid, err := NewGroupIDRandom()
	if err != nil {
		t.Fatalf("NewGroupIDRandom: %v", err)
	}
	g, err := NewGroup(gid, ciphersuite.MLS128DHKEMP256, kp, kpPriv,
		WithExtensions([]Extension{{Type: 0x0005, Data: extData}}))
	if err != nil {
		t.Fatalf("NewGroup: %v", err)
	}
	// Precondition: the external sender's key must be found in the GroupContext.
	if _, err := g.getExternalSenderSigningKey(0); err != nil {
		t.Fatalf("precondition: getExternalSenderSigningKey(0): %v", err)
	}
	return g, memberSig, extSig
}

// externalSenderProposalMessage builds and signs, as external sender 0, a PublicMessage that carries
// proposal p.
func externalSenderProposalMessage(t *testing.T, g *Group, extSig *ciphersuite.SignaturePrivateKey, p *Proposal) *framing.PublicMessage {
	t.Helper()
	content := framing.FramedContent{
		GroupID: g.groupID.AsSlice(),
		Epoch:   g.epoch.AsUint64(),
		Sender:  framing.Sender{Type: framing.SenderTypeExternal, SenderIndex: 0},
		Body:    framing.ProposalBody{Data: ProposalMarshal(p)},
	}
	pm, err := framing.NewPublicMessage(content, extSig, g.groupContext.Marshal(), nil, g.cipherSuite)
	if err != nil {
		t.Fatalf("framing.NewPublicMessage (external sender): %v", err)
	}
	return pm
}

// externalInitProposal builds an ExternalInit proposal with a 32-byte kem_output.
func externalInitProposal() *Proposal {
	return &Proposal{
		Type:         ProposalTypeExternalInit,
		ExternalInit: &ExternalInitProposal{KemOutput: bytes.Repeat([]byte{0xAB}, 32)},
	}
}

// addProposalForNewMember builds an Add proposal for a new joiner with a valid KeyPackage.
func addProposalForNewMember(t *testing.T, _ *Group) *Proposal {
	t.Helper()
	cred, _, err := credentials.GenerateCredentialWithKey([]byte("joiner"))
	if err != nil {
		t.Fatalf("GenerateCredentialWithKey: %v", err)
	}
	kp, _, err := keypackages.Generate(cred, keypackages.MLS128DHKEMP256)
	if err != nil {
		t.Fatalf("keypackages.Generate: %v", err)
	}
	return NewAddProposal(kp)
}

// TestRegularCommitSucceedsWithExternalSenderConfigured checks that a regular Commit without external
// proposals passes in this setup. If it fails, the setup is broken and the other tests of this file
// mean nothing.
func TestRegularCommitSucceedsWithExternalSenderConfigured(t *testing.T) {
	g, memberSig, _ := newGroupWithExternalSender(t)
	staged, err := g.Commit(memberSig, memberSig.PublicKey(), nil)
	if err != nil {
		t.Fatalf("regular Commit without external proposals failed: %v", err)
	}
	if staged == nil {
		t.Fatal("staged commit is nil")
	}
}

// TestCommitCoversAllowedExternalSenderProposal checks that a GroupContextExtensions proposal from an
// external sender (allowed by RFC 9420 §12.1.8) is stored, and that a later Commit covers it.
func TestCommitCoversAllowedExternalSenderProposal(t *testing.T) {
	g, memberSig, extSig := newGroupWithExternalSender(t)
	gce := &Proposal{
		Type:                   ProposalTypeGroupContextExtensions,
		GroupContextExtensions: &ContextExtensionsProposal{Extensions: g.groupContext.Extensions},
	}
	pm := externalSenderProposalMessage(t, g, extSig, gce)
	if err := g.ProcessPublicMessage(pm); err != nil {
		t.Fatalf("ProcessPublicMessage(external GCE) failed: %v", err)
	}
	if len(g.proposals.Proposals) != 1 {
		t.Fatalf("stored=%d, want 1", len(g.proposals.Proposals))
	}
	if _, err := g.Commit(memberSig, memberSig.PublicKey(), nil); err != nil {
		t.Fatalf("Commit with an allowed external GCE failed: %v", err)
	}
}

// TestProcessPublicMessageAcceptsAllowedExternalSenderTypes checks that every proposal type that RFC 9420
// §12.1.8 allows from an external sender is still accepted on receipt and stored, so the external
// sender rule does not reject too much.
func TestProcessPublicMessageAcceptsAllowedExternalSenderTypes(t *testing.T) {
	cases := []struct {
		name string
		prop func(t *testing.T, g *Group) *Proposal
	}{
		{"add", addProposalForNewMember},
		{"remove", func(*testing.T, *Group) *Proposal {
			return &Proposal{Type: ProposalTypeRemove, Remove: &RemoveProposal{Removed: 0}}
		}},
		{"psk", func(*testing.T, *Group) *Proposal {
			return &Proposal{Type: ProposalTypePreSharedKey, PreSharedKey: &PreSharedKeyProposal{
				PskType: 1,
				PskID:   PskID{PskType: 1, ID: []byte("psk-id"), Nonce: make([]byte, 32)},
			}}
		}},
		{"reinit", func(*testing.T, *Group) *Proposal {
			return &Proposal{Type: ProposalTypeReInit, ReInit: &ReInitProposal{
				GroupID:     []byte("reinit-group"),
				Version:     1,
				CipherSuite: keypackages.MLS128DHKEMP256,
			}}
		}},
		{"group_context_extensions", func(_ *testing.T, g *Group) *Proposal {
			return &Proposal{
				Type:                   ProposalTypeGroupContextExtensions,
				GroupContextExtensions: &ContextExtensionsProposal{Extensions: g.groupContext.Extensions},
			}
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			g, _, extSig := newGroupWithExternalSender(t)
			pm := externalSenderProposalMessage(t, g, extSig, tc.prop(t, g))
			if err := g.ProcessPublicMessage(pm); err != nil {
				t.Fatalf("ProcessPublicMessage(external %s) err=%v, want nil", tc.name, err)
			}
			if n := len(g.proposals.Proposals); n != 1 {
				t.Fatalf("stored=%d, want 1", n)
			}
		})
	}
}

// TestProcessPublicMessageRejectsExternalInitFromExternalSender checks that an ExternalInit from an
// external sender is rejected with an error that wraps ErrInvalidProposal, that nothing is stored, and
// that a regular Commit is not blocked.
func TestProcessPublicMessageRejectsExternalInitFromExternalSender(t *testing.T) {
	g, memberSig, extSig := newGroupWithExternalSender(t)
	pm := externalSenderProposalMessage(t, g, extSig, externalInitProposal())

	err := g.ProcessPublicMessage(pm)
	if err == nil {
		t.Fatal("ProcessPublicMessage accepted an ExternalInit from an external sender (RFC 9420 §12.1.8)")
	}
	if !errors.Is(err, ErrInvalidProposal) {
		t.Fatalf("err=%v, want it to wrap ErrInvalidProposal", err)
	}
	if !strings.Contains(err.Error(), "external sender cannot send proposal type") {
		t.Fatalf("err=%v, want the external sender rule", err)
	}
	if n := len(g.proposals.Proposals); n != 0 {
		t.Fatalf("stored=%d after a rejected ExternalInit, want 0", n)
	}
	if _, err := g.Commit(memberSig, memberSig.PublicKey(), nil); err != nil {
		t.Fatalf("regular Commit blocked after a rejected ExternalInit: %v", err)
	}
}

// TestFilterProposalsForCommitRefusesStoredExternalInit checks that IsExternal is set for stored
// proposals from external senders, so a stored ExternalInit is refused by the external sender rule. The
// same type from a tree member keeps the internal rule.
func TestFilterProposalsForCommitRefusesStoredExternalInit(t *testing.T) {
	g, _, _ := newGroupWithExternalSender(t)
	// Stored directly, as a proposal restored from an earlier state would be.
	g.proposals.AddProposal(externalInitProposal(), LeafNodeIndex(g.ratchetTree.NumLeaves))

	_, err := g.FilterProposalsForCommit(nil)
	if err == nil {
		t.Fatal("FilterProposalsForCommit accepted a stored ExternalInit from an external sender")
	}
	if !errors.Is(err, ErrInvalidProposal) {
		t.Fatalf("err=%v, want it to wrap ErrInvalidProposal", err)
	}
	if !strings.Contains(err.Error(), "external sender cannot send proposal type") {
		t.Fatalf("err=%v, want the external sender rule (IsExternal must be set)", err)
	}

	pf := NewProposalFilter(g.groupContext, g.ownLeafIndex, g.members, g.cipherSuite, g.ratchetTree)
	err = pf.validateSingleProposal(FilteredProposal{Proposal: externalInitProposal(), Sender: g.ownLeafIndex}, nil)
	if err == nil || !strings.Contains(err.Error(), "external init from internal sender") {
		t.Fatalf("ExternalInit from a tree member: err=%v, want external init from internal sender", err)
	}
}
