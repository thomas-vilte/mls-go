// forgedCommitWithExtra returns the commit of base with extra appended to its proposal list, re-signed
// with sigKey. The UpdatePath stays the one of base. The receiver checks the proposal list before it
// processes the path, so the forged list does not have to match the path.
func forgedCommitWithExtra(t *testing.T, base *StagedCommit, extra ProposalOrRef, sigKey *ciphersuite.SignaturePrivateKey) *framing.AuthenticatedContent {
	t.Helper()
	body, ok := base.authenticatedContent.Content.Body.(framing.CommitBody)
	if !ok {
		t.Fatal("base commit has no commit body")
	}
	commit, err := UnmarshalCommit(body.Data)
	if err != nil {
		t.Fatalf("UnmarshalCommit(base): %v", err)
	}
	commit.Proposals = append(commit.Proposals, extra)
	forged := *base.authenticatedContent
	forged.Content.Body = framing.CommitBody{Data: commit.Marshal()}
	sig, err := ciphersuite.SignWithLabel(sigKey, "FramedContentTBS", forged.MarshalTBS())
	if err != nil {
		t.Fatalf("re-signing the forged commit: %v", err)
	}
	forged.Auth.Signature = sig
	return &forged
}

// TestCommitWithCommitterOwnUpdateIsInvalid checks that the proposal list of a commit is invalid if it
// contains an Update generated by the committer (RFC 9420 §12.2). That holds for an Update sent by value and for
// one sent by reference, when the committer builds the commit and when another member receives it. An Update from
// another member, sent by reference, is still accepted.
func TestCommitWithCommitterOwnUpdateIsInvalid(t *testing.T) {
	t.Run("generation/own_update_by_value_refused", func(t *testing.T) {
		m := newUpdateProposalTestMembers(t)
		if _, err := m.bobGroup.SelfUpdate(m.bob.sigPriv); err != nil {
			t.Fatalf("SelfUpdate(bob): %v", err)
		}
		_, err := m.bobGroup.Commit(m.bob.sigPriv, m.bob.sigPub, nil)
		if !errors.Is(err, ErrInvalidProposal) || !strings.Contains(err.Error(), "generated by the committer") {
			t.Fatalf("Commit(bob) with his own Update by value: err = %v, want ErrInvalidProposal (generated by the committer)", err)
		}
	})

	t.Run("generation/own_update_by_reference_refused", func(t *testing.T) {
		m := newUpdateProposalTestMembers(t)
		update, pm := newSignedUpdateMessage(t, m.bobGroup, m.bob.sigPriv)
		m.bobGroup.RegisterProposalRef(update, publicMessageProposalRef(pm, m.bobGroup.cipherSuite))

		_, err := m.bobGroup.Commit(m.bob.sigPriv, m.bob.sigPub, nil)
		if !errors.Is(err, ErrInvalidProposal) || !strings.Contains(err.Error(), "generated by the committer") {
			t.Fatalf("Commit(bob) with his own Update by reference: err = %v, want ErrInvalidProposal (generated by the committer)", err)
		}
	})

	t.Run("reception/own_update_by_value_refused", func(t *testing.T) {
		m := newUpdateProposalTestMembers(t)
		update, err := m.bobGroup.SelfUpdate(m.bob.sigPriv)
		if err != nil {
			t.Fatalf("SelfUpdate(bob): %v", err)
		}
		// The honest API refuses to build this commit, so the base is the empty commit of bob, and the
		// Update is appended by hand. The base is built after bob's store is cleared.
		m.bobGroup.ClearProposals()
		base, err := m.bobGroup.Commit(m.bob.sigPriv, m.bob.sigPub, nil)
		if err != nil {
			t.Fatalf("Commit(bob, empty base): %v", err)
		}
		forged := forgedCommitWithExtra(t, base, ProposalOrRef{Proposal: update}, m.bob.sigPriv)

		err = m.aliceGroup.ProcessReceivedCommit(forged, treesync.LeafIndex(m.bobGroup.ownLeafIndex), m.aliceGroup.myLeafEncryptionKey)
		if !errors.Is(err, ErrInvalidProposal) {
			t.Fatalf("alice.ProcessReceivedCommit(bob's commit with his own Update by value): err = %v, want ErrInvalidProposal", err)
		}
		if got := m.aliceGroup.epoch.AsUint64(); got != 1 {
			t.Fatalf("refused commit advanced alice to epoch %d, want 1", got)
		}
	})

	t.Run("reception/own_update_by_reference_refused", func(t *testing.T) {
		m := newUpdateProposalTestMembers(t)
		update, pm := newSignedUpdateMessage(t, m.bobGroup, m.bob.sigPriv)
		for _, g := range []*Group{m.aliceGroup, m.charlieGroup} {
			if err := g.ProcessPublicMessage(pm); err != nil {
				t.Fatalf("ProcessPublicMessage(bob update): %v", err)
			}
		}
		ref := publicMessageProposalRef(pm, m.bobGroup.cipherSuite)
		m.bobGroup.RegisterProposalRef(update, ref)
		m.bobGroup.ClearProposals()
		base, err := m.bobGroup.Commit(m.bob.sigPriv, m.bob.sigPub, nil)
		if err != nil {
			t.Fatalf("Commit(bob, empty base): %v", err)
		}
		forged := forgedCommitWithExtra(t, base, ProposalOrRef{ProposalRef: ref}, m.bob.sigPriv)

		err = m.aliceGroup.ProcessReceivedCommit(forged, treesync.LeafIndex(m.bobGroup.ownLeafIndex), m.aliceGroup.myLeafEncryptionKey)
		if !errors.Is(err, ErrInvalidProposal) || !strings.Contains(err.Error(), "generated by the committer") {
			t.Fatalf("alice.ProcessReceivedCommit(bob's commit with his own Update by reference): err = %v, want ErrInvalidProposal (generated by the committer)", err)
		}
		if got := m.aliceGroup.epoch.AsUint64(); got != 1 {
			t.Fatalf("refused commit advanced alice to epoch %d, want 1", got)
		}
	})

	t.Run("control/other_member_update_by_reference_accepted", func(t *testing.T) {
		m := newUpdateProposalTestMembers(t)
		_, pm := newSignedUpdateMessage(t, m.aliceGroup, m.alice.sigPriv)
		for _, g := range []*Group{m.bobGroup, m.charlieGroup} {
			if err := g.ProcessPublicMessage(pm); err != nil {
				t.Fatalf("ProcessPublicMessage(alice update): %v", err)
			}
		}
		sc, err := m.bobGroup.Commit(m.bob.sigPriv, m.bob.sigPub, nil)
		if err != nil {
			t.Fatalf("Commit(bob) with alice's Update by reference: %v", err)
		}
		if err := m.charlieGroup.ProcessReceivedCommit(sc.authenticatedContent, treesync.LeafIndex(m.bobGroup.ownLeafIndex), m.charlieGroup.myLeafEncryptionKey); err != nil {
			t.Fatalf("charlie.ProcessReceivedCommit(bob's commit with alice's Update by reference): %v", err)
		}
	})
}
